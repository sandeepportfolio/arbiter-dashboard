-- 008_drop_legacy_trades_table.sql
-- Drop the empty legacy ``trades`` table.
--
-- ``trades`` predates the current execution-persistence stack (migration
-- 001 introduced ``execution_arbs`` + ``execution_orders`` + ``execution_fills``).
-- It has no readers or writers in the Python code today — grep
-- "FROM trades\b|INTO trades\b|UPDATE trades\b" returns zero matches — and
-- production rows count is 0.  Its narrower schema (``arb_id varchar(20)``
-- vs the canonical ``execution_arbs.arb_id varchar(40)`` widened by
-- migration 004) is also actively hazardous: any code that still wrote
-- here would truncate hash-based recovery arb_ids (e.g. ``STRAND-…-12hex``,
-- 32 chars; ``RECOV-{sha1[:16]}``).
--
-- Drop it outright rather than widening: keeping a dead table around just
-- accumulates schema-management overhead and tempts future code to start
-- using it again, splitting the source-of-truth on trades across two
-- tables.  Reads/writes against trade history must continue to use the
-- ``execution_arbs`` family.
--
-- Forward-only — do not edit this file after it is applied to any env.

DROP TABLE IF EXISTS trades CASCADE;
